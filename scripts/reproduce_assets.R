#!/usr/bin/env Rscript
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L) stop('Usage: Rscript scripts/reproduce_assets.R NEW_OUTPUT_DIRECTORY')
script <- sub('^--file=', '', grep('^--file=', commandArgs(), value = TRUE)[1L])
script <- gsub('~+~', ' ', script, fixed=TRUE)
root <- normalizePath(file.path(dirname(script), '..'), mustWork = TRUE)
output <- path.expand(args[1L])
if (!grepl('^/',output)) output <- file.path(getwd(),output)
output <- normalizePath(output, mustWork = FALSE)
if (file.exists(output)) stop('Choose a new output directory: ', output)
setwd(root)
source('computation/R/nelder_mead.R')
source('computation/R/mad_methods.R')
source('computation/R/studies.R')
source('computation/R/optimizer_checks.R')
source('computation/R/assets.R')
finalize_r_assets(full_base = 'computation/generated_r/full', output_dir = output)
cat('Rebuilt numerical assets from saved records in ', output, '\n', sep = '')
